CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(10) NOT NULL CHECK(role IN ('ADMIN','VERIFIER','USER')),
 phone VARCHAR(10) NOT NULL DEFAULT '',
 gender VARCHAR(30) NOT NULL DEFAULT '',
 address VARCHAR(500) NOT NULL DEFAULT '',
 city VARCHAR(80) NOT NULL DEFAULT '',
 state VARCHAR(80) NOT NULL DEFAULT '',
 birth_date VARCHAR(10) NOT NULL DEFAULT '',
 spam_strikes INT NOT NULL DEFAULT 0 CHECK(spam_strikes >= 0),
 blocked BOOLEAN NOT NULL DEFAULT FALSE,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS forums (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(160) NOT NULL,
 body VARCHAR(20000) NOT NULL,
 category_id BIGINT NOT NULL REFERENCES categories(id),
 created_by BIGINT NOT NULL REFERENCES accounts(id),
 image_bytes BINARY LARGE OBJECT,
 image_type VARCHAR(20),
 archived BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 forum_id BIGINT NOT NULL REFERENCES forums(id),
 author_id BIGINT NOT NULL REFERENCES accounts(id),
 body VARCHAR(3000) NOT NULL,
 status VARCHAR(10) NOT NULL CHECK(status IN ('PUBLISHED','PENDING','REJECTED')),
 matched_terms VARCHAR(4000) NOT NULL,
 reviewed_by BIGINT REFERENCES accounts(id),
 review_note VARCHAR(500) NOT NULL DEFAULT '',
 reviewed_at TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 action VARCHAR(60) NOT NULL,
 detail VARCHAR(500) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_comments_forum ON comments(forum_id,status,created_at);
CREATE INDEX IF NOT EXISTS idx_comments_author ON comments(author_id);
